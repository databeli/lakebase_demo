CREATE SCHEMA IF NOT EXISTS shop;

-- ---------------------------------------------------------------------
-- customers
-- ---------------------------------------------------------------------
CREATE TABLE shop.customers (
    customer_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name    TEXT        NOT NULL,
    email        TEXT        NOT NULL UNIQUE,
    city         TEXT        NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- orders
-- product_id deliberately has no foreign key: products live in Unity
-- Catalog and arrive here later as a read-only synced table (step 5).
-- ---------------------------------------------------------------------
CREATE TABLE shop.orders (
    order_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  INT         NOT NULL REFERENCES shop.customers (customer_id),
    product_id   INT         NOT NULL,
    quantity     INT         NOT NULL CHECK (quantity > 0),
    status       TEXT        NOT NULL DEFAULT 'PLACED'
                 CHECK (status IN ('PLACED', 'SHIPPED', 'DELIVERED', 'CANCELLED')),
    order_ts     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

